// 위기 신호 감지 — 모델에 보내기 **전에** 잡는다.
//
// 왜 앞에서 잡나:
//   이 앱의 페르소나는 "나도 그때 그랬는데, 지나와 보니 —" 톤으로 공감하게
//   만들어져 있다(buildSystemPrompt). 자해·극단적 선택 얘기에 그 톤이 나오면 위험하다.
//   프롬프트에 "이럴 땐 이렇게 답해"를 적는 방법도 있지만 그건 **확률**이다.
//   여기서 거르면 모델이 그 문장을 아예 보지 못한다 — **확정**이다.
//
// 좁게 잡는다:
//   애매하면 안 잡는다. 잘못 잡으면 "배고파 죽겠다"에 상담전화가 떠서 앱이
//   이상해지고, 정작 필요할 때의 안내까지 가볍게 읽힌다.
//   그래서 관용어로 흔한 "죽겠다", "목매다"는 아예 목록에 넣지 않았다.
// ---------------------------------------------------------------------------

/**
 * 위기 신호일 때 보여줄 문구 (지웅님이 정한 문장).
 *
 * 줄 사이에 빈 줄을 두지 않는다 — splitMessageParagraphs가 빈 줄에서 잘라
 * 말풍선 3개로 쪼개고, 타이핑 애니메이션과 함께 하나씩 뜬다.
 * 이건 페르소나를 멈추는 말이라 한 번에 와야 한다.
 * 줄바꿈 자체는 말풍선의 whitespace-pre-line 으로 그대로 보인다.
 */
export const CRISIS_REPLY = `잠깐, 지금은 '미래의 나'와의 이야기를 멈출게.
지금 많이 힘든 것 같아. 혼자 두고 싶지 않아서 하는 말이야.
자살예방 상담전화 109 — 24시간 언제든 받아.
나는 앱이라서 전문 상담을 대신할 수는 없어. 너의 이야기는 계속 들을게.`

/**
 * 위기 표현이 아닌데 걸리는 말들. 검사 전에 지운다.
 * - 자살골/자살점: 축구
 * - 유서 깊은: "오래된"이라는 뜻
 */
const NOT_CRISIS: RegExp[] = [/자살골/g, /자살점/g, /유서가?깊/g]

/**
 * 위기 표현. 띄어쓰기를 지운 문장에 대고 본다 ("죽고 싶어" == "죽고싶어").
 *
 * 일부러 뺀 것:
 * - `죽겠`  — "배고파 죽겠다", "웃겨 죽겠어" 가 훨씬 흔하다
 * - `목매`  — "성적에 목매지 마" 처럼 관용어로 쓰인다
 */
const CRISIS: RegExp[] = [
  /자살/,
  /자해/,
  /죽고싶/,
  /죽어버리/,
  /죽어야겠/,
  /살기싫/,
  /살고싶지않/,
  /사라지고싶/,
  /없어지고싶/,
  /목숨을?끊/,
  /목을?매달/,
  /뛰어내리/,
  /손목을?긋/,
  // "그어" / "그었" 둘 다 — 테스트에서 "손목을 그었어"가 안 잡혀서 잡았다
  /손목을?그[어었]/,
  /유서/,
]

export function isCrisisMessage(text: string): boolean {
  if (!text) return false
  let t = text.replace(/\s+/g, '')
  for (const skip of NOT_CRISIS) t = t.replace(skip, '')
  return CRISIS.some((p) => p.test(t))
}
